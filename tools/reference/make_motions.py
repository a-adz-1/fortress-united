"""
Builds Game/Weapons/ViewModelMotions.cs from TFC's first-person models, so
our melee weapons are held and swung the way TFC frames them.

    python3 tools/reference/make_motions.py <tfc models dir>

Only measurements are taken (the path of the hand, elbow and weapon end in
view space for each frame); no Valve data is copied. TFC's view models are
drawn at 90 degrees horizontal on 4:3 (73.7 vertical); ours use a fixed 54
vertical, so sideways and up/down offsets are scaled to keep the same place
on screen.
"""
import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(__file__)
SCALE = 0.5095 / 0.75     # tan(54/2) / tan(73.7/2)

# our weapon -> (TFC model, idle sequence, swing sequence)
WEAPONS = {
    "Prod": ("v_tfc_crowbar.mdl", "idle1", "attack1"),
    "Spanner": ("v_tfc_spanner.mdl", "idle", "attack1"),
    "Killswitch": ("v_tfc_knife.mdl", "idle", "stab"),
}


def measure(path):
    out = tempfile.mktemp(suffix=".json")
    subprocess.run([sys.executable, os.path.join(HERE, "gs_viewmodel.py"), path, "--json", out], check=True, capture_output=True)
    return json.load(open(out))


def scaled(p):
    return (p[0] * SCALE, p[1] * SCALE, p[2])


def norm(v):
    l = sum(c * c for c in v) ** 0.5
    return tuple(c / l for c in v)


def frames(seq):
    rows = []
    for f in seq["frames"]:
        h, e, t = scaled(f["hand"]), scaled(f["elbow"]), scaled(f["far"])
        d = norm(tuple(t[i] - h[i] for i in range(3)))
        rows.append((h, d, e))
    return rows


def vec(v):
    return f"new Vector3({v[0]:.4f}f, {v[1]:.4f}f, {v[2]:.4f}f)"


def main():
    models = sys.argv[1]
    parts = []
    for name, (mdl, idle, swing) in WEAPONS.items():
        d = measure(os.path.join(models, mdl))
        seqs = {s["label"]: s for s in d["sequences"]}
        iq, sq = seqs[idle], seqs[swing]
        ifr, sfr = frames(iq), frames(sq)
        # the hit lands where the weapon reaches furthest forward
        hit = max(range(len(sq["frames"])), key=lambda i: sq["frames"][i]["far"][2])
        def arr(rows, k):
            return ", ".join(vec(r[k]) for r in rows)
        parts.append(f'''        public static readonly ViewModelMotion {name} = new ViewModelMotion
        {{
            IdleFps = {iq["fps"]:.1f}f, SwingFps = {sq["fps"]:.1f}f, HitFrame = {hit},
            IdleHand = new[] {{ {arr(ifr, 0)} }},
            IdleDir = new[] {{ {arr(ifr, 1)} }},
            IdleElbow = new[] {{ {arr(ifr, 2)} }},
            SwingHand = new[] {{ {arr(sfr, 0)} }},
            SwingDir = new[] {{ {arr(sfr, 1)} }},
            SwingElbow = new[] {{ {arr(sfr, 2)} }},
        }};  // from {mdl}: {idle}, {swing}
''')
        print(f"{name}: {mdl} {idle} {len(ifr)} frames, {swing} {len(sfr)} frames, hit at {hit}")
    src = f'''// Generated by tools/reference/make_motions.py from measurements of TFC's
// first-person models (hand, elbow and weapon-end paths); do not edit by hand.
using UnityEngine;

namespace FortressUnited.Game
{{
    /// <summary>
    /// How a melee weapon sits and swings in first person, frame by frame, in
    /// view-model camera space (metres): where the hand is, which way the
    /// weapon points out of it, and where the elbow is.
    /// </summary>
    public sealed class ViewModelMotion
    {{
        public float IdleFps, SwingFps;
        public int HitFrame;
        public Vector3[] IdleHand, IdleDir, IdleElbow, SwingHand, SwingDir, SwingElbow;

        public float SwingSeconds => SwingHand.Length / SwingFps;
        public float HitSeconds => HitFrame / SwingFps;

        static Vector3 Sample(Vector3[] a, float frame, bool loop)
        {{
            int n = a.Length;
            if (n == 1) return a[0];
            if (loop) frame = Mathf.Repeat(frame, n);
            else frame = Mathf.Clamp(frame, 0, n - 1);
            int i = Mathf.FloorToInt(frame);
            int j = loop ? (i + 1) % n : Mathf.Min(i + 1, n - 1);
            return Vector3.Lerp(a[i], a[j], frame - i);
        }}

        /// <summary>The pose at a time in the idle loop, or in the swing when swingTime is 0 or more.</summary>
        public void Pose(float idleTime, float swingTime, out Vector3 hand, out Vector3 dir, out Vector3 elbow)
        {{
            if (swingTime >= 0)
            {{
                float f = swingTime * SwingFps;
                hand = Sample(SwingHand, f, false);
                dir = Sample(SwingDir, f, false).normalized;
                elbow = Sample(SwingElbow, f, false);
            }}
            else
            {{
                float f = idleTime * IdleFps;
                hand = Sample(IdleHand, f, true);
                dir = Sample(IdleDir, f, true).normalized;
                elbow = Sample(IdleElbow, f, true);
            }}
        }}
    }}

    public static class ViewModelMotions
    {{
{"".join(parts)}    }}
}}
'''
    dst = os.path.join(HERE, "..", "..", "Assets", "FortressUnited", "Game", "Weapons", "ViewModelMotions.cs")
    open(dst, "w").write(src)
    print("wrote", os.path.normpath(dst))


if __name__ == "__main__":
    main()
